/**
 * Copies the compiled EscrowFlow ABI + bytecode from the Hardhat artifacts into the app.
 *   npm run contracts:compile && npm run contracts:abi
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const root = path.resolve(__dirname, "..");
const artifactPath = path.join(root, "contracts", "artifacts", "contracts", "EscrowFlow.sol", "EscrowFlow.json");
const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as { abi: unknown[]; bytecode: string };

const outDir = path.join(root, "src", "config", "abi");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  path.join(outDir, "escrowFlow.ts"),
  `// AUTO-GENERATED by scripts/export-abi.ts from contracts/artifacts — do not edit by hand.\n` +
    `export const escrowFlowAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
// Bytecode is only needed by the deploy script; keep it out of the app bundle.
mkdirSync(path.join(root, "scripts", "build"), { recursive: true });
writeFileSync(
  path.join(root, "scripts", "build", "EscrowFlow.bytecode.json"),
  JSON.stringify({ bytecode: artifact.bytecode }),
);
console.log(`Exported ABI (${artifact.abi.length} entries) and bytecode (${(artifact.bytecode.length - 2) / 2} bytes).`);
